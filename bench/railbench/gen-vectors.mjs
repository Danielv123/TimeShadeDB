// Writes the rail geometry test vectors (docs/v3/RAIL-GEOMETRY.md section 7) from the reference model and from real
// recorded runs:
//   - pieces: for every rail type and direction seen in the runs, a real piece (position, direction, the ends the game
//     reported) and the model's point and tangent at nine arc lengths;
//   - trains: real carriages as the game placed them, with the rail path under them and the leading carriage's front
//     joint fitted on it (trainfit.mjs), for checking an implementation's carriage placement against the game.
//
//   node bench/railbench/gen-vectors.mjs --run bizz --run aron --run l1n3 [--per 3] [--cars 4] [--work <dir>]
//       [--out docs/v3/rail-geometry-vectors.json]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { readGroundTruth } from "./gt.mjs";
import { RailNet } from "./railnet.mjs";
import { fitTrain, carriageAxes } from "./trainfit.mjs";
import { railLength, railPoint, orientationOf, placeTrain, R, CURVE_A_LENGTH, CURVE_B_LENGTH, CURVE_B_END_RADIUS,
	HALF_DIAGONAL_LENGTH, LEGACY_R, LEGACY_STRAIGHT, LEGACY_CURVE_LENGTH, RAMP_LENGTH } from "./railgeom.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const runs = args.flatMap((a, i) => (a === "--run" ? [args[i + 1]] : []));
const option = (name, fallback) => {
	const i = args.indexOf(name);
	return i >= 0 && args[i + 1] !== undefined ? args[i + 1] : fallback;
};
const work = path.resolve(option("--work", process.env.RAILBENCH_WORK ?? "G:/project_files/timeshade-v3-work/railbench"));
const PER = Number(option("--per", 3));
const CARS = Number(option("--cars", 4));
const outPath = path.resolve(option("--out", path.join(here, "..", "..", "docs", "v3", "rail-geometry-vectors.json")));

const r6 = (v) => Number(v.toFixed(6));
const r9 = (v) => Number(v.toFixed(9));

const out = {
	format: 1,
	about: "Rail centre-line geometry and rolling stock placement test vectors for docs/v3/RAIL-GEOMETRY.md. Generated by "
		+ "bench/railbench/gen-vectors.mjs from the reference model (bench/railbench/railgeom.mjs) and from carriages recorded "
		+ "in Factorio 2.1.19.",
	units: "Map coordinates in tiles (x east, y south); directions are 16-way defines.direction values; orientations are "
		+ "Factorio orientations in turns (0 north, 0.25 east); s is the game's rail distance from the piece's front end.",
	constants: { R, CURVE_A_LENGTH, CURVE_B_LENGTH, CURVE_B_END_RADIUS: r9(CURVE_B_END_RADIUS), HALF_DIAGONAL_LENGTH: r9(HALF_DIAGONAL_LENGTH),
		LEGACY_R: r9(LEGACY_R), LEGACY_STRAIGHT: r9(LEGACY_STRAIGHT), LEGACY_CURVE_LENGTH: r9(LEGACY_CURVE_LENGTH), RAMP_LENGTH: r9(RAMP_LENGTH),
		JOINT_DISTANCE: 4, CONNECTION_DISTANCE: 3 },
	tolerance: {
		piece_points: 1e-6,
		piece_ends_vs_game: 1e-6,
		piece_ends_vs_game_legacy_curved_rail: 0.012,
		train_position_vs_game: 0.02,
		train_orientation_vs_game_deg: 0.25,
		note: "piece_points: an implementation of the spec's formulas against the reference model (the ramp's inverse "
			+ "length table may differ by up to 1e-4; use 1e-3 for rail-ramp). The game itself places joints with "
			+ "polynomial fits of the curves (within 0.01 tile of the formulas) on a 1/256 tile grid. The legacy curved rail ends "
			+ "0.011 tile from its connection point (its last part is drawn with the arc formula).",
	},
	pieces: [],
	trains: [],
};

const seenPiece = new Set();
const trainCases = new Map(); // category -> count

for (const name of runs) {
	const dir = path.join(work, "runs", name);
	const gt = readGroundTruth(path.join(dir, "write", "script-output", "railbench"));
	const net = new RailNet(gt.rails);
	for (const r of gt.rails) {
		const key = `${r.type}/${r.dir}`;
		if (seenPiece.has(key)) {
			continue;
		}
		seenPiece.add(key);
		const L = railLength(r.type, r.dir);
		const points = [];
		for (let i = 0; i <= 8; i++) {
			const s = (L * i) / 8;
			const p = railPoint(r, s);
			points.push([r9(s), r9(p.x), r9(p.y), r9(orientationOf(p.tx, p.ty))]);
		}
		out.pieces.push({ type: r.type, dir: r.dir, x: r.x, y: r.y, length: r9(L), game_length: r.length,
			front_end: [r.ends[0].x, r.ends[0].y, r.ends[0].dir], back_end: [r.ends[1].x, r.ends[1].y, r.ends[1].dir],
			points, source: name });
	}
	// train cases: lines of moving trains whose leading carriage's front joint is on a piece of each category
	for (const tr of gt.trains) {
		if (tr.n < 2) {
			continue;
		}
		for (let k = 0; k < tr.ticks.length; k += 7) {
			if (tr.speed[k] === 0) {
				continue;
			}
			const ax = carriageAxes(tr, k);
			const c = net.near(tr.surface, ax.cx[0] + 2 * ax.ux[0], ax.cy[0] + 2 * ax.uy[0], ax.ux[0], ax.uy[0], 0.3, 0.9);
			if (c.length !== 1) {
				continue;
			}
			const cat = c[0].r.type;
			if ((trainCases.get(cat) ?? 0) >= PER || c[0].s < 0.5 || c[0].s > c[0].r.L - 0.5) {
				continue;
			}
			const fit = fitTrain(net, tr, k);
			if (!fit) {
				continue;
			}
			const m = Math.min(CARS, tr.n);
			// the pieces under the first m carriages, and the leading front joint on them
			const cum = [0];
			for (const p of fit.path) {
				cum.push(cum[cum.length - 1] + railLength(p.type, p.dir));
			}
			const lo = fit.Uf[0] - 7 * (m - 1) - 4 - 0.5;
			let first = cum.findIndex((v, i) => i < fit.path.length && cum[i + 1] > lo);
			first = Math.max(0, first);
			let last = fit.path.length - 1;
			while (last > first && cum[last] > fit.Uf[0] + 0.5) {
				last--;
			}
			const pathCut = fit.path.slice(first, last + 1);
			const u0 = fit.Uf[0] - cum[first];
			const placed = placeTrain(pathCut, u0, m, 4, 3);
			const cars = [];
			let worst = 0;
			for (let i = 0; i < m; i++) {
				const b = k * tr.stride + 3 * i;
				const x = tr.cars[b] / 256;
				const y = tr.cars[b + 1] / 256;
				const o = tr.cars[b + 2] / 65536;
				cars.push([x, y, o]);
				worst = Math.max(worst, Math.hypot(placed[i].x - x, placed[i].y - y));
			}
			if (worst > 0.02) {
				continue; // not a clean case (a projection on the wrong piece of a switch); the measurement is geometry.mjs's job
			}
			trainCases.set(cat, (trainCases.get(cat) ?? 0) + 1);
			out.trains.push({ category: cat, source: `${name} train ${tr.id} tick ${tr.ticks[k]}`,
				path: pathCut.map(p => ({ type: p.type, x: p.x, y: p.y, dir: p.dir, rev: p.rev })), u0: r6(u0),
				game_carriages: cars,
				note: "game orientations are the carriage's own facing (a carriage facing the train's rear is half a turn off "
					+ "the model's front-pointing orientation); compare them as axes" });
		}
	}
}
out.pieces.sort((a, b) => (a.type < b.type ? -1 : a.type > b.type ? 1 : a.dir - b.dir));
fs.writeFileSync(outPath, JSON.stringify(out, null, 1) + "\n");
console.log(`${out.pieces.length} pieces, ${out.trains.length} train cases (${JSON.stringify(Object.fromEntries(trainCases))}) -> ${outPath}`);
